#!/usr/bin/env python3
"""
Generates the resource (endpoint) layer of every MagicPay SDK from spec.py.

    python3 generator/generate.py

The hand-written core of each SDK (HTTP, signing, errors) lives next to the
generated files and is not touched by this script.
"""
import os
import re
import shutil
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from spec import AUTH_KINDS, RESOURCES  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = "AUTO-GENERATED by generator/generate.py from generator/spec.py. Do not edit by hand."
PARAM_RE = re.compile(r"\{(\w+)\}")


def pascal(s):
    return "".join(p[:1].upper() + p[1:] for p in s.split("_"))


def camel(s):
    p = pascal(s)
    return p[:1].lower() + p[1:]


def xml(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def params(path):
    return PARAM_RE.findall(path)


def auth_note(auth):
    """Human-readable auth requirement used in doc comments."""
    return "Auth: " + AUTH_KINDS[auth] + "."


def write(rel, content):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print("wrote", rel)


# --------------------------------------------------------------------------- python
def gen_python():
    out = [f'"""{HEADER}"""', "from typing import Any, Mapping, Optional", "",
           "from ._base import Resource, path_param", "", ""]
    for rname, r in RESOURCES.items():
        cls = pascal(rname) + "Resource"
        out.append(f"class {cls}(Resource):")
        out.append(f'    """{r["doc"]}"""')
        out.append("")
        for name, method, path, body, query, auth, summary in r["endpoints"]:
            ps = params(path)
            args = ["self"] + [f"{p}: Any" for p in ps]
            if body:
                args.append("body: Mapping[str, Any]")
            if query:
                args.append("query: Optional[Mapping[str, Any]] = None")
            fpath = PARAM_RE.sub(lambda m: "{path_param(" + m.group(1) + ")}", path)
            pexpr = f'f"{fpath}"' if ps else f'"{path}"'
            call = f'self._client.request("{method}", {pexpr}'
            if body:
                call += ", body=body"
            if query:
                call += ", query=query"
            call += ")"
            out.append(f"    def {name}({', '.join(args)}) -> Any:")
            out.append(f'        """{summary}  `{method} {path}`  {auth_note(auth)}"""')
            out.append(f"        return {call}")
            out.append("")
        out.append("")
    out.append("RESOURCE_CLASSES = {")
    for rname in RESOURCES:
        out.append(f'    "{rname}": {pascal(rname)}Resource,')
    out.append("}")
    write("python/magicpay/resources.py", "\n".join(out) + "\n")


# --------------------------------------------------------------------------- .NET
def gen_dotnet():
    out = [f"// {HEADER}", "#nullable enable", "using System.Collections.Generic;",
           "using System.Net.Http;", "using System.Text.Json.Nodes;", "using System.Threading;",
           "using System.Threading.Tasks;", "", "namespace MagicPay", "{"]
    # client partial with resource properties
    out.append("    public sealed partial class MagicPayClient")
    out.append("    {")
    for rname in RESOURCES:
        out.append(f"        /// <summary>{xml(RESOURCES[rname]['doc'])}</summary>")
        out.append(f"        public {pascal(rname)}Resource {pascal(rname)} {{ get; private set; }} = null!;")
    out.append("")
    out.append("        private void InitResources()")
    out.append("        {")
    for rname in RESOURCES:
        out.append(f"            {pascal(rname)} = new {pascal(rname)}Resource(this);")
    out.append("        }")
    out.append("    }")
    out.append("")
    for rname, r in RESOURCES.items():
        cls = pascal(rname) + "Resource"
        out.append(f"    /// <summary>{xml(r['doc'])}</summary>")
        out.append(f"    public sealed class {cls}")
        out.append("    {")
        out.append("        private readonly MagicPayClient _client;")
        out.append(f"        internal {cls}(MagicPayClient client) {{ _client = client; }}")
        out.append("")
        for name, method, path, body, query, auth, summary in r["endpoints"]:
            ps = params(path)
            args = [f"object {camel(p)}" for p in ps]
            if body:
                args.append("object body")
            if query:
                args.append("IReadOnlyDictionary<string, object?>? query = null")
            args.append("CancellationToken cancellationToken = default")
            fpath = PARAM_RE.sub(lambda m: "{MagicPayClient.PathParam(" + camel(m.group(1)) + ")}", path)
            pexpr = f'$"{fpath}"' if ps else f'"{path}"'
            http = {"GET": "HttpMethod.Get", "POST": "HttpMethod.Post", "PUT": "HttpMethod.Put",
                    "DELETE": "HttpMethod.Delete", "PATCH": "MagicPayClient.Patch"}[method]
            out.append(f"        /// <summary>{xml(summary)} <c>{method} {path}</c> {xml(auth_note(auth))}</summary>")
            out.append(f"        public Task<JsonNode?> {pascal(name)}Async({', '.join(args)})")
            out.append(f"            => _client.SendAsync({http}, {pexpr}, "
                       f"{'body' if body else 'null'}, {'query' if query else 'null'}, cancellationToken);")
            out.append("")
        out.append("    }")
        out.append("")
    out.append("}")
    write("dotnet/src/MagicPay/Resources.g.cs", "\n".join(out) + "\n")


# --------------------------------------------------------------------------- rust
def gen_rust():
    out = [f"//! {HEADER}", "#![allow(clippy::too_many_arguments)]", "",
           "use std::fmt::Display;", "", "use reqwest::Method;", "use serde::Serialize;",
           "use serde_json::Value;", "", "use crate::client::{path_param, Client};",
           "use crate::error::Result;", "", "impl Client {"]
    for rname, r in RESOURCES.items():
        out.append(f"    /// {r['doc']}")
        out.append(f"    pub fn {rname}(&self) -> {pascal(rname)}<'_> {{")
        out.append(f"        {pascal(rname)} {{ client: self }}")
        out.append("    }")
    out.append("}")
    out.append("")
    for rname, r in RESOURCES.items():
        st = pascal(rname)
        out.append(f"/// {r['doc']}")
        out.append("#[derive(Debug, Clone, Copy)]")
        out.append(f"pub struct {st}<'a> {{")
        out.append("    client: &'a Client,")
        out.append("}")
        out.append("")
        out.append(f"impl<'a> {st}<'a> {{")
        for name, method, path, body, query, auth, summary in r["endpoints"]:
            ps = params(path)
            args = ["&self"] + [f"{p}: impl Display" for p in ps]
            if body:
                args.append("body: &(impl Serialize + ?Sized)")
            if query:
                args.append("query: &[(&str, &str)]")
            if ps:
                fpath = PARAM_RE.sub("{}", path)
                pexpr = f'&format!("{fpath}", ' + ", ".join(f"path_param({p})?" for p in ps) + ")"
            else:
                pexpr = f'"{path}"'
            body_expr = "Some(serde_json::to_value(body)?)" if body else "None"
            q_expr = "query" if query else "&[]"
            out.append(f"    /// {summary} `{method} {path}` {auth_note(auth)}")
            out.append(f"    pub async fn {name}({', '.join(args)}) -> Result<Value> {{")
            out.append(f"        self.client")
            out.append(f"            .request(Method::{method}, {pexpr}, {body_expr}, {q_expr})")
            out.append(f"            .await")
            out.append("    }")
            out.append("")
        out[-1:] = ["}", ""]
    write("rust/src/resources.rs", "\n".join(out))
    rustfmt("rust/src/resources.rs")


def rustfmt(rel):
    """Format a generated Rust file so regenerating leaves no diff.

    Uses a local rustfmt, else Docker (image MAGICPAY_RUSTFMT_IMAGE, default rust:1.82);
    skipped with a warning if neither works or MAGICPAY_SKIP_RUSTFMT=1.
    """
    if os.environ.get("MAGICPAY_SKIP_RUSTFMT") == "1":
        print("rustfmt skipped (MAGICPAY_SKIP_RUSTFMT=1)")
        return
    crate = os.path.join(ROOT, "rust")
    target = os.path.relpath(os.path.join(ROOT, rel), crate).replace(os.sep, "/")
    if shutil.which("rustfmt"):
        cmd = ["rustfmt", "--edition", "2021", target]
    elif shutil.which("docker"):
        image = os.environ.get("MAGICPAY_RUSTFMT_IMAGE", "rust:1.82")
        cmd = ["docker", "run", "--rm", "-v", f"{crate}:/w", "-w", "/w", image, "sh", "-c",
               "(rustfmt --version >/dev/null 2>&1 || rustup component add rustfmt >/dev/null 2>&1)"
               f" && rustfmt --edition 2021 {target}"]
    else:
        print("warning: rustfmt not found (local or Docker); run `cargo fmt` in rust/ before committing")
        return
    result = subprocess.run(cmd, cwd=crate, env=dict(os.environ, MSYS_NO_PATHCONV="1"),
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if result.returncode != 0:
        print("warning: rustfmt failed; run `cargo fmt` in rust/ before committing\n" + result.stdout[-2000:])
    else:
        print("formatted", rel)


# --------------------------------------------------------------------------- php
def gen_php():
    props, inits = [], []
    for rname, r in RESOURCES.items():
        cls = pascal(rname)
        lines = ["<?php", "", f"// {HEADER}", "", "declare(strict_types=1);", "",
                 "namespace MagicPay\\Resource;", "", "/**", f" * {r['doc']}", " */",
                 f"final class {cls} extends AbstractResource", "{"]
        for name, method, path, body, query, auth, summary in r["endpoints"]:
            ps = params(path)
            args = [f"string|int ${camel(p)}" for p in ps]
            if body:
                args.append("array|object $body")
            if query:
                args.append("array $query = []")
            fpath = PARAM_RE.sub(lambda m: "' . self::p($" + camel(m.group(1)) + ") . '", path)
            pexpr = f"'{fpath}'".replace(" . ''", "")
            call = f"$this->client->request('{method}', {pexpr}, {'$body' if body else 'null'}, {'$query' if query else '[]'})"
            lines += ["    /**", f"     * {summary}", "     *", f"     * {method} {path}", f"     * {auth_note(auth)}", "     *",
                      "     * @return array<string, mixed>|list<mixed>|null", "     */",
                      f"    public function {camel(name)}({', '.join(args)}): ?array",
                      "    {", f"        return {call};", "    }", ""]
        lines[-1:] = ["}", ""]
        write(f"php/src/Resource/{cls}.php", "\n".join(lines))
        props.append(f"    public Resource\\{cls} ${camel(rname)};")
        inits.append(f"        $this->{camel(rname)} = new Resource\\{cls}($this);")
    trait = ["<?php", "", f"// {HEADER}", "", "declare(strict_types=1);", "", "namespace MagicPay;", "",
             "/** @internal */", "trait ResourcesTrait", "{"] + props + ["",
             "    private function initResources(): void", "    {"] + inits + ["    }", "}", ""]
    write("php/src/ResourcesTrait.php", "\n".join(trait))


# --------------------------------------------------------------------------- docs
def gen_endpoints_md():
    out = [f"<!-- {HEADER} -->", "# Endpoint reference", "",
           "Every endpoint the SDKs wrap and its method name in each SDK.", "",
           "Auth column: **Signed (V1/V2)** = signature headers (SDK default V2); **Signed (V2 only)** = V1 is "
           "rejected; **Bearer** = call `login()` first (or set `access_token`); **Signed or Bearer** = either a "
           "valid signature or a Bearer token; **None** = public.", ""]
    for rname, r in RESOURCES.items():
        out += [f"## `{rname}` — {r['doc']}", "",
                "| HTTP | Path | Auth | Python | .NET | Rust | PHP |", "|---|---|---|---|---|---|---|"]
        for name, method, path, body, query, auth, summary in r["endpoints"]:
            out.append(f"| {method} | `{path}` | {AUTH_KINDS[auth]} | `mp.{rname}.{name}()` | `{pascal(rname)}.{pascal(name)}Async()` "
                       f"| `{rname}().{name}()` | `->{camel(rname)}->{camel(name)}()` |")
        out.append("")
    write("ENDPOINTS.md", "\n".join(out))


if __name__ == "__main__":
    gen_python()
    gen_dotnet()
    gen_rust()
    gen_php()
    gen_endpoints_md()
